static void synth_cp437_8x16(oyk_u8 ch, oyk_u8* g) {
    memset(g, 0, 16);
    if (ch >= 0x20U && ch <= 0x7EU) {
        memcpy(g, k_ascii_8x16[ch - 0x20U], 16);
        return;
    }
    switch (ch) {
        case 0xB0U: { /* Light shade */
            for (int r = 0; r < 16; ++r) g[r] = (r & 1) ? 0x22U : 0x88U;
            break;
        }
        case 0xB1U: { /* Medium shade */
            for (int r = 0; r < 16; ++r) g[r] = (r & 1) ? 0x55U : 0xAAU;
            break;
        }
        case 0xB2U: { /* Dark shade */
            for (int r = 0; r < 16; ++r) g[r] = (r & 1) ? 0xDDU : 0x77U;
            break;
        }
        case 0xDBU: { /* Full block */
            memset(g, 0xFF, 16);
            break;
        }
        case 0xDCU: { /* Lower half block */
            memset(g + 8, 0xFF, 8);
            break;
        }
        case 0xDFU: { /* Upper half block */
            memset(g, 0xFF, 8);
            break;
        }
        case 0xC4U: { /* Horizontal line */
            g[7] = 0xFFU;
            break;
        }
        case 0xB3U: { /* Vertical line */
            for (int r = 0; r < 16; ++r) g[r] = 0x18U;
            break;
        }
        case 0xDAU: { /* Top-left corner */
            g[7] = 0x1FU;
            for (int r = 8; r < 16; ++r) g[r] = 0x18U;
            break;
        }
        case 0xBFU: { /* Top-right corner */
            g[7] = 0xF8U;
            for (int r = 8; r < 16; ++r) g[r] = 0x18U;
            break;
        }
        case 0xC0U: { /* Bottom-left corner */
            for (int r = 0; r < 8; ++r) g[r] = 0x18U;
            g[7] = 0x1FU;
            break;
        }
        case 0xD9U: { /* Bottom-right corner */
            for (int r = 0; r < 8; ++r) g[r] = 0x18U;
            g[7] = 0xF8U;
            break;
        }
        case 0xC3U: { /* Left T */
            for (int r = 0; r < 16; ++r) g[r] = 0x18U;
            g[7] = 0x1FU;
            break;
        }
        case 0xB4U: { /* Right T */
            for (int r = 0; r < 16; ++r) g[r] = 0x18U;
            g[7] = 0xF8U;
            break;
        }
        case 0xC2U: { /* Top T */
            g[7] = 0xFFU;
            for (int r = 8; r < 16; ++r) g[r] = 0x18U;
            break;
        }
        case 0xC1U: { /* Bottom T */
            for (int r = 0; r < 8; ++r) g[r] = 0x18U;
            g[7] = 0xFFU;
            break;
        }
        case 0xC5U: { /* Cross */
            for (int r = 0; r < 16; ++r) g[r] = 0x18U;
            g[7] = 0xFFU;
            break;
        }
        case 0xCDU: { /* Double H */
            g[6] = 0xFFU;
            g[9] = 0xFFU;
            break;
        }
        case 0xBAU: { /* Double V */
            for (int r = 0; r < 16; ++r) g[r] = 0x24U;
            break;
        }
        case 0xC9U: { /* Double TL */
            g[6] = 0x3FU;
            g[7] = 0x20U;
            g[8] = 0x20U;
            g[9] = 0x27U;
            for (int r = 10; r < 16; ++r) g[r] = 0x24U;
            break;
        }
        case 0xBBU: { /* Double TR */
            g[6] = 0xFCU;
            g[7] = 0x04U;
            g[8] = 0x04U;
            g[9] = 0xE4U;
            for (int r = 10; r < 16; ++r) g[r] = 0x24U;
            break;
        }
        case 0xC8U: { /* Double BL */
            for (int r = 0; r < 6; ++r) g[r] = 0x24U;
            g[6] = 0x27U;
            g[7] = 0x20U;
            g[8] = 0x20U;
            g[9] = 0x3FU;
            break;
        }
        case 0xBCU: { /* Double BR */
            for (int r = 0; r < 6; ++r) g[r] = 0x24U;
            g[6] = 0xE4U;
            g[7] = 0x04U;
            g[8] = 0x04U;
            g[9] = 0xFCU;
            break;
        }
        case 0x07U:
        case 0xFAU: { /* Bullet / Middle dot */
            g[7] = 0x18U;
            g[8] = 0x18U;
            break;
        }
        case 0x1EU: { /* Up triangle */
            g[5] = 0x10U; g[6] = 0x38U; g[7] = 0x7CU; g[8] = 0xFEU;
            break;
        }
        case 0x1FU: { /* Down triangle */
            g[5] = 0xFEU; g[6] = 0x7CU; g[7] = 0x38U; g[8] = 0x10U;
            break;
        }
        case 0x1AU: { /* Right arrow */
            g[7] = 0x7CU; g[6] = 0x18U; g[8] = 0x18U;
            break;
        }
        case 0x1BU: { /* Left arrow */
            g[7] = 0x3EU; g[6] = 0x18U; g[8] = 0x18U;
            break;
        }
        default: {
            /* Fallback space for unmapped control codes */
            break;
        }
    }
}

